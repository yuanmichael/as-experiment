"""Test the CASSVG(V/I/L)(Y/F)STDTQYF motif family as a unit, in Komech 2018.

The project's headline result is one sequence, `CASSVGLYSTDTQYF`. Hanson et al.
2020 (Arthritis Rheumatol 72:1289) show it is one member of a six-sequence
family generated by two substitutions, and that their strongest member is a
different one -- `CASSVGLFSTDTQYF`, in 12 of 37 HLA-B27+ AS patients and absent
from every B27+ control. Yang et al. 2022 (Nature 612:771) solved structures for
three members and name a fourth related receptor, AS4.3 = `CASSVATYSTDTQYF`.

Every sequence in PRESPECIFIED below was named in one of those papers before we
looked at it, so testing their union carries no selection leakage -- unlike the
167-sequence burden panel, whose membership was chosen from these same labels.

EXPLORATORY holds two sequences our own screen surfaced that sit one edit from a
family member but carry Leu at residue 95, outside Hanson's motif. They are
reported separately and never pooled into the primary test.

Presence is >=2 reads after thinning every subject to 800,000 junction reads,
reusing clono_sweep's loader, thinner and carrier matrix so the definition is
identical to `build_panel.py`. Native-depth presence is reported alongside as a
sensitivity check, because AS libraries are deeper than healthy ones and
presence is depth-sensitive.

    python scripts/motif_family_test.py --tables <dir of Komech *_cdr3.tsv.gz>
"""
from __future__ import annotations

import argparse
import os
import sys

import numpy as np
import pandas as pd
from scipy.stats import fisher_exact, mannwhitneyu

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from clono_sweep import carrier_matrix, load_tables, thin  # noqa: E402

THIN_DEPTH = 800_000
SEED = 0

# Named in the literature before we looked. Hanson's motif is the six-member
# grid CASSVG[VIL][YF]STDTQYF; Yang's AS4.3 is a fourth named receptor.
PRESPECIFIED = {
    "CASSVGLYSTDTQYF": "Hanson motif; Yang AS4.1; Faham/Komech",
    "CASSVGLFSTDTQYF": "Hanson motif + headline clone; Yang AS4.2",
    "CASSVGVYSTDTQYF": "Hanson motif",
    "CASSVGVFSTDTQYF": "Hanson motif",
    "CASSVGIYSTDTQYF": "Hanson motif",
    "CASSVGIFSTDTQYF": "Hanson motif",
    "CASSVATYSTDTQYF": "Yang AS4.3 (structure solved)",
}

# Our own screen found these; one edit from a member, but Leu at residue 95.
EXPLORATORY = {
    "CASSLGLFSTDTQYF": "one edit from CASSVGLFSTDTQYF",
    "CASSLGLYSTDTQYF": "one edit from CASSVGLYSTDTQYF",
}

KNOWN = "CASSVGLYSTDTQYF"   # the incremental-value reference


def presence_frame(df: pd.DataFrame, panel: list[str]) -> pd.DataFrame:
    """One row per subject, one boolean column per panel sequence."""
    mat, subjects, cdr3s = carrier_matrix(df, "presence")
    index = {c: i for i, c in enumerate(cdr3s)}
    cols = {}
    for seq in panel:
        j = index.get(seq)
        cols[seq] = (np.zeros(len(subjects), bool) if j is None
                     else np.asarray(mat[:, j].todense()).ravel() > 0)
    out = pd.DataFrame(cols, index=subjects)
    grp = df.drop_duplicates("subject").set_index("subject")["group"]
    out.insert(0, "group", grp.reindex(out.index).to_numpy())
    return out


def two_by_two(pres: pd.DataFrame, case: str, mask: np.ndarray) -> dict:
    is_case = (pres["group"] == case).to_numpy()
    a = int((mask & is_case).sum())
    b = int((mask & ~is_case).sum())
    n_case, n_ctrl = int(is_case.sum()), int((~is_case).sum())
    table = [[a, n_case - a], [b, n_ctrl - b]]
    return {
        "case_carriers": a, "n_case": n_case,
        "ctrl_carriers": b, "n_ctrl": n_ctrl,
        "sensitivity": a / n_case if n_case else float("nan"),
        "specificity": (n_ctrl - b) / n_ctrl if n_ctrl else float("nan"),
        "fisher_p": fisher_exact(table, alternative="greater")[1],
        "fisher_p_two_sided": fisher_exact(table)[1],
    }


def report(label: str, r: dict) -> None:
    print(f"  {label:<46} AS {r['case_carriers']:>2}/{r['n_case']:<2} "
          f"({r['sensitivity']:5.1%})   healthy {r['ctrl_carriers']}/{r['n_ctrl']}   "
          f"p = {r['fisher_p']:.4f}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tables", required=True)
    ap.add_argument("--case", default="as")
    ap.add_argument("--ctrl", default="healthy")
    ap.add_argument("--depth", type=int, default=THIN_DEPTH)
    ap.add_argument("--out", default="data/panel/motif_family_test.tsv")
    args = ap.parse_args()

    panel = list(PRESPECIFIED) + list(EXPLORATORY)
    df = load_tables(args.tables)
    runs = df["subject"].nunique()
    print(f"loaded {len(df):,} (subject, clonotype) rows for {runs} subjects")

    df = df[df["group"].isin([args.case, args.ctrl])]
    rng = np.random.default_rng(SEED)
    thinned = thin(df, args.depth, rng)

    pres_thin = presence_frame(thinned, panel)
    pres_native = presence_frame(df, panel)
    n_case = int((pres_thin["group"] == args.case).sum())
    n_ctrl = int((pres_thin["group"] == args.ctrl).sum())
    print(f"after thinning to {args.depth:,}: {n_case} {args.case}, "
          f"{n_ctrl} {args.ctrl}\n")

    rows = []
    for seq in panel:
        arm = "prespecified" if seq in PRESPECIFIED else "exploratory"
        for depth_label, pres in (("thinned", pres_thin), ("native", pres_native)):
            r = two_by_two(pres, args.case, pres[seq].to_numpy())
            rows.append(dict(cdr3=seq, arm=arm, depth=depth_label,
                             source=PRESPECIFIED.get(seq) or EXPLORATORY[seq], **r))

    print("PER SEQUENCE (thinned, >=2 reads)")
    for seq in panel:
        tag = " " if seq in PRESPECIFIED else "*"
        report(tag + seq, two_by_two(pres_thin, args.case, pres_thin[seq].to_numpy()))
    print("  * exploratory, not in the primary test\n")

    pre = list(PRESPECIFIED)
    for depth_label, pres in (("thinned", pres_thin), ("native", pres_native)):
        union = pres[pre].to_numpy().any(axis=1)
        known = pres[KNOWN].to_numpy()
        r_union = two_by_two(pres, args.case, union)
        r_known = two_by_two(pres, args.case, known)
        rows.append(dict(cdr3="UNION_prespecified", arm="prespecified",
                         depth=depth_label, source="7 literature-named", **r_union))
        rows.append(dict(cdr3="UNION_plus_exploratory", arm="combined",
                         depth=depth_label, source="9 sequences",
                         **two_by_two(pres, args.case,
                                      pres[panel].to_numpy().any(axis=1))))
        print(f"PRIMARY TEST ({depth_label})")
        report("union of 7 pre-specified sequences", r_union)
        report(f"{KNOWN} alone (reference)", r_known)
        extra = int((union & ~known & (pres["group"] == args.case)).sum())
        print(f"  union adds {extra} AS patient(s) the known clone misses\n")

    counts = pres_thin[pre].sum(axis=1).to_numpy()
    is_case = (pres_thin["group"] == args.case).to_numpy()
    u, p_mw = mannwhitneyu(counts[is_case], counts[~is_case], alternative="greater")
    auc = u / (is_case.sum() * (~is_case).sum())
    print("CARRIER COUNT (0-7, thinned), threshold-free")
    print(f"  AS median {np.median(counts[is_case]):.1f} "
          f"(range {counts[is_case].min()}-{counts[is_case].max()}), "
          f"healthy median {np.median(counts[~is_case]):.1f} "
          f"(range {counts[~is_case].min()}-{counts[~is_case].max()})")
    print(f"  Mann-Whitney p = {p_mw:.4f}, rank-biserial AUC = {auc:.3f}\n")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    pd.DataFrame(rows).to_csv(args.out, sep="\t", index=False, float_format="%.6g")
    subj_out = args.out.replace(".tsv", "_subjects.tsv")
    pres_thin.assign(n_prespecified=counts).to_csv(subj_out, sep="\t")
    print(f"wrote {args.out} and {subj_out}")


if __name__ == "__main__":
    main()
